// genFile 对应 preview 中的 {name, path, code}；path 同时是 ZIP 条目名。
type genFile struct {
	Name string `json:"name"`
	Path string `json:"path"`
	Code string `json:"code"`
}

// renderFiles：7 个骨架文件——后端四层（模型 / SQL / 服务 / 路由）、前端 API 与页面、菜单 SQL。
// 后端骨架按本工程 scaffold-go 的结构输出：一个 internal/<module> 包，用 framework 的查询辅助与路由注册方式。
func renderFiles(table framework.Row, columns []framework.Row) []genFile {
	tableName := framework.AsString(table["tableName"])
	className := framework.AsString(table["className"])
	module := framework.AsString(table["module"])
	resource := decapitalize(className)
	files := []genFile{
		{Path: fmt.Sprintf("backend/internal/%s/%s_model.go", module, tableName), Code: modelCode(module, tableName, className, columns)},
		{Path: fmt.Sprintf("backend/internal/%s/%s_sql.go", module, tableName), Code: sqlCode(module, tableName, className, columns)},
		{Path: fmt.Sprintf("backend/internal/%s/%s_service.go", module, tableName), Code: serviceCode(module, className)},
		{Path: fmt.Sprintf("backend/internal/%s/%s_handler.go", module, tableName), Code: handlerCode(module, className, resource)},
		{Path: fmt.Sprintf("frontend/src/api/%s/%s.ts", module, resource), Code: apiCode(module, resource)},
		{Path: fmt.Sprintf("frontend/src/views/%s/%s/index.vue", module, resource), Code: viewCode(tableName, className, columns)},
		{Path: fmt.Sprintf("sql/%s_menu.sql", tableName), Code: menuSql(tableName, className, module, resource)},
	}
	for i := range files {
		files[i].Name = files[i].Path[strings.LastIndex(files[i].Path, "/")+1:]
	}
	return files
}

// activeFileName 预览默认选中的文件：路由文件。
func activeFileName(tableName string) string { return tableName + "_handler.go" }

// gofmt 对生成的 Go 源码做格式化；格式化失败时原样返回。
func gofmt(src string) string {
	if out, err := format.Source([]byte(src)); err == nil {
		return string(out)
	}
	return src
}

// goType 把导入时记录的字段类型映射为 Go 类型。
// 时间列用 string：framework.SelectRows 把 DATETIME 输出为 "yyyy-MM-ddTHH:mm:ss" 字符串。
func goType(javaType string) string {
	switch javaType {
	case "Long":
		return "int64"
	case "Integer":
		return "int"
	case "BigDecimal":
		return "float64"
	}
	return "string"
}

// modelCode 模型结构体：字段名为列名的大驼峰，json 标签为小驼峰，注释取列注释。
func modelCode(module, tableName, className string, columns []framework.Row) string {
	var fields strings.Builder
	for _, column := range columns {
		field := framework.AsString(column["javaField"])
		line := fmt.Sprintf("\t%s %s `json:\"%s\"`", upperFirst(field), goType(framework.AsString(column["javaType"])), field)
		if comment := framework.StrOrEmpty(column["comment"]); comment != "" {
			line += " // " + comment
		}
		fields.WriteString(line + "\n")
	}
	return gofmt(fmt.Sprintf(`// Code generated by scaffold-go 代码生成器；按需修改。
package %s

// %s 对应表 %s。
type %s struct {
%s}
`, module, className, tableName, className, fields.String()))
}

// sqlCode SQL 层：计数与分页列表，列别名即 JSON 字段名；条件按需补充。
func sqlCode(module, tableName, className string, columns []framework.Row) string {
	selects := make([]string, 0, len(columns))
	orderBy := ""
	for i, column := range columns {
		col := framework.AsString(column["col"])
		selects = append(selects, fmt.Sprintf("%s AS %s", col, framework.AsString(column["javaField"])))
		if i == 0 {
			orderBy = "\n\t\tORDER BY " + col + " DESC"
		}
	}
	if len(selects) == 0 {
		selects = append(selects, "*")
	}
	return gofmt(fmt.Sprintf(`// Code generated by scaffold-go 代码生成器；按需修改。
package %s

import (
	"context"

	"scaffold/internal/framework"
)

// count%s 统计 %s 行数。
func count%s(ctx context.Context, q framework.Querier) (int64, error) {
	return framework.SelectInt64(ctx, q, "SELECT COUNT(*) FROM %s")
}

// select%sList 分页查询 %s，列别名即接口返回的字段名。
func select%sList(ctx context.Context, q framework.Querier, offset, pageSize int) ([]framework.Row, error) {
	return framework.SelectRows(ctx, q, `+"`"+`
		SELECT %s
		FROM %s%s
		LIMIT ?, ?`+"`"+`, offset, pageSize)
}
`, module, className, tableName, className, tableName, className, tableName, className,
		strings.Join(selects, ",\n\t\t       "), tableName, orderBy))
}

// serviceCode 服务层：分页列表；增删改按需实现，写操作用 framework.Tx。
func serviceCode(module, className string) string {
	return gofmt(fmt.Sprintf(`// Code generated by scaffold-go 代码生成器；按需修改。
package %s

import (
	"context"
	"database/sql"

	"scaffold/internal/framework"
)

// %sService 业务逻辑；新增 / 修改 / 删除按需实现，写操作放在 framework.Tx 中。
type %sService struct{ db *sql.DB }

func New%sService(db *sql.DB) *%sService { return &%sService{db: db} }

// List 分页列表。
func (s *%sService) List(ctx context.Context, q framework.PageQuery) (framework.PageResult[framework.Row], error) {
	total, err := count%s(ctx, s.db)
	if err != nil {
		return framework.PageResult[framework.Row]{}, err
	}
	rows, err := select%sList(ctx, s.db, q.Offset(), q.NormalizedPageSize())
	if err != nil {
		return framework.PageResult[framework.Row]{}, err
	}
	return framework.PageOf(rows, total, q), nil
}
`, module, className, className, className, className, className, className, className, className))
}

// handlerCode 路由层：注册列表接口并绑定权限码；在 internal/app/app.go 中调用 Register 函数。
func handlerCode(module, className, resource string) string {
	return gofmt(fmt.Sprintf(`// Code generated by scaffold-go 代码生成器；按需修改。
package %s

import (
	"net/http"

	"scaffold/internal/framework"
)

// Register%sRoutes 注册 /api/%s/%s 路由；在 internal/app/app.go 的 New 中调用：
//
//	%s.Register%sRoutes(mux, sec, %s.New%sService(db))
//
// 写接口按 framework.OperLog(rec, "%s管理", "新增") 的方式加操作日志。
func Register%sRoutes(mux *http.ServeMux, sec *framework.Security, s *%sService) {
	mux.Handle("GET /api/%s/%s", framework.Handle(func(w http.ResponseWriter, r *http.Request) error {
		q, err := framework.ParsePage(r)
		if err != nil {
			return err
		}
		page, err := s.List(r.Context(), q)
		if err != nil {
			return err
		}
		return framework.OK(w, r, page)
	}, sec.Perm("%s:%s:list")))
}
`, module, className, module, resource, module, className, module, className, className,
		className, className, module, resource, module, resource))
}

// apiCode 前端 API 文件。
func apiCode(module, resource string) string {
	return fmt.Sprintf(`import { httpClient } from '@/api/http'

export const %sApi = {
  list: (query?: Record<string, unknown>) => httpClient.get('/%s/%s', query as any),
}
`, resource, module, resource)
}

// viewCode 前端页面占位；按 ListPage / useListPage 规范补齐。
func viewCode(tableName, className string, columns []framework.Row) string {
	firstListField := "id"
	for _, column := range columns {
		if enabled(column["list"]) {
			firstListField = framework.AsString(column["javaField"])
			break
		}
	}
	return fmt.Sprintf(`<script setup lang="ts">
const tableName = '%s'
const className = '%s'
const primaryField = '%s'
</script>

<template>
  <div>
    <h1>{{ className }}</h1>
    <p>{{ tableName }} · {{ primaryField }}</p>
  </div>
</template>
`, tableName, className, firstListField)
}

// menuSql 菜单与权限码。
func menuSql(tableName, className, module, resource string) string {
	return fmt.Sprintf(`-- %s 菜单权限
INSERT INTO sys_menu (id, parent_id, menu_name, menu_type, path, component, permission, sort, visible, status, create_by, update_by)
SELECT COALESCE(MAX(id), 0) + 1, 0, '%s管理', 'menu', '/%s/%s', '%s/%s/index', '%s:%s:list', 1, 1, 1, 'system', 'system'
FROM sys_menu;
`, tableName, className, module, resource, module, resource, module, resource)
}

// enabled：Number → intValue()==1，否则 Boolean.TRUE.equals。
func enabled(value any) bool {
	switch v := value.(type) {
	case int64:
		return v == 1
	case bool:
		return v
	}
	return false
}

// ---------- 命名辅助 ----------

func isBlank(s string) bool { return strings.TrimSpace(s) == "" }

func upperFirst(value string) string {
	if isBlank(value) {
		return value
	}
	r, n := utf8.DecodeRuneInString(value)
	return string(unicode.ToUpper(r)) + value[n:]
}

// decapitalize
func decapitalize(value string) string {
	if isBlank(value) {
		return value
	}
	r, n := utf8.DecodeRuneInString(value)
	return string(unicode.ToLower(r)) + value[n:]
}

// moduleName：表名前缀作为模块名，sys → system。
func moduleName(tableName string) string {
	module := "system"
	if split := strings.IndexByte(tableName, '_'); split > 0 {
		module = tableName[:split]
	}
	if module == "sys" {
		return "system"
	}
	return module
}

// businessName
func businessName(tableName string) string {
	raw := tableName
	if split := strings.IndexByte(tableName, '_'); split > 0 {
		raw = tableName[split+1:]
	}
	return lowerCamel(raw)
}

// upperCamel
func upperCamel(value string) string { return upperFirst(lowerCamel(value)) }

// lowerCamel：toLowerCase(Locale.ROOT).split("_")，跳过空白段。
func lowerCamel(value string) string {
	if isBlank(value) {
		return value
	}
	var b strings.Builder
	for _, part := range strings.Split(strings.ToLower(value), "_") {
		if isBlank(part) {
			continue
		}
		if b.Len() == 0 {
			b.WriteString(part)
		} else {
			b.WriteString(upperFirst(part))
		}
	}
	return b.String()
}

// javaType：导入时记录的字段类型（沿用原有字段 java_type 与前端「字段映射」展示）。
func javaType(dataType string) string {
	switch dataType {
	case "bigint":
		return "Long"
	case "int", "integer", "smallint", "tinyint":
		return "Integer"
	case "decimal", "numeric":
		return "BigDecimal"
	case "datetime", "timestamp", "date", "time":
		return "LocalDateTime"
	}
	return "String"
}

// formType
func formType(dataType string) string {
	switch dataType {
	case "text", "longtext", "mediumtext":
		return "文本域"
	case "int", "integer", "smallint", "tinyint", "bigint", "decimal", "numeric":
		return "数字框"
	case "datetime", "timestamp", "date", "time":
		return "日期框"
	}
	return "文本框"
}

// queryField
func queryField(columnName string) bool {
	lower := strings.ToLower(columnName)
	return strings.Contains(lower, "name") || strings.Contains(lower, "code") ||
		strings.Contains(lower, "status") || strings.Contains(lower, "type")
}
